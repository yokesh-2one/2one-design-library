/*
  Visual/a11y coverage scorecard (C12).

  Reads the committed baselines under tests/visual/__screenshots__ and the component
  universe from graph.json, and reports — mechanically, no AI — WHAT the visual suite
  verifies: how many cases, across which dimensions (themes × viewports, interaction
  states, ARIA, RTL, forced-colors), and which real components have no case yet.

  This turns "we test the UI completely" from a claim into a tracked number. It writes
  docs/visual-coverage.md and prints a summary. Run: node scripts/visual-coverage.mjs
*/
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const shotsDir = join(root, 'tests/visual/__screenshots__')

const ls = (d) => (existsSync(d) ? readdirSync(d) : [])
// {caseId}[-{state}]-{vp}-{theme}-{platform}.{png|aria.yml}
const TAIL = /-(mobile|laptop|desktop)-(light|dark)-(win32|linux)\.(png|aria\.yml)$/
const STATES = ['hover', 'focus', 'open']

function argOf(file) {
  const m = file.match(TAIL)
  return m ? file.slice(0, m.index) : null
}
/** Distinct "args" (caseId or caseId-state) in a spec dir, ignoring platform dupes. */
function argsIn(spec) {
  const set = new Set()
  for (const f of ls(join(shotsDir, spec))) {
    const a = argOf(f)
    if (a) set.add(a)
  }
  return set
}

const screenshots = argsIn('screenshots.spec.ts')
const ariaSet = argsIn('aria.spec.ts')
const rtlSet = argsIn('rtl.spec.ts')
const fcSet = argsIn('forced-colors.spec.ts')

// states: split "caseId-state" into a map caseId -> Set(states)
const stateMap = new Map()
for (const a of argsIn('states.spec.ts')) {
  const st = STATES.find((s) => a.endsWith(`-${s}`))
  if (!st) continue
  const id = a.slice(0, -(st.length + 1))
  if (!stateMap.has(id)) stateMap.set(id, new Set())
  stateMap.get(id).add(st)
}

// Every screenshot case is also an axe case (axe runs on ALL_CASES); use screenshots
// plus dashboard (axe-covered, screenshot-excluded historically) as the axe universe.
const allCases = [...new Set([...screenshots, ...stateMap.keys(), ...ariaSet])].sort()

const graph = JSON.parse(readFileSync(join(root, 'graph.json'), 'utf8'))
const components = graph.nodes
  .filter((n) => n.type === 'component' || n.type === 'component-2one')
  .map((n) => n.id.split(':')[1])
  .sort()

// A component is "cased" if a screenshot case matches its name (directly, as name-open,
// or via a known composition that renders it).
const COMPOSITION_COVERS = {
  sidebar: 'app-shell', // AppShell renders the Sidebar
}
const cased = (name) =>
  screenshots.has(name) ||
  screenshots.has(`${name}-open`) ||
  ariaSet.has(name) ||
  (COMPOSITION_COVERS[name] && screenshots.has(COMPOSITION_COVERS[name]))
const gaps = components.filter((c) => !cased(c))

// ---- report ----------------------------------------------------------------
const tick = (b) => (b ? '✓' : '·')
const rows = allCases.map((id) => {
  const st = stateMap.get(id)
  return `| ${id} | ${tick(screenshots.has(id))} | ${st ? [...st].sort().join(' ') : '·'} | ${tick(ariaSet.has(id))} | ${tick(rtlSet.has(id))} | ${tick(fcSet.has(id))} |`
})

const md = `# Visual & a11y coverage

_Generated by \`node scripts/visual-coverage.mjs\` from the committed baselines — do not edit by hand._

Every case is also verified by axe (WCAG), the console/no-network check, and (responsive
surfaces) the no-overflow check. Screenshots run in **2 themes × 3 viewports**; ARIA, RTL
and forced-colors run on focused, sufficient subsets.

## Summary

- **${allCases.length}** cases under test
- **${screenshots.size}** with pixel screenshots (× 2 themes × 3 viewports = ${screenshots.size * 6} baselines)
- **${stateMap.size}** with interaction-state shots (hover/focus/open)
- **${ariaSet.size}** with ARIA-tree snapshots (semantic)
- **${rtlSet.size}** under RTL, **${fcSet.size}** under forced-colors (High Contrast)
- **${components.length}** library components; **${components.length - gaps.length}** have a case, **${gaps.length}** rely on composition/other coverage

## Per-case coverage

| case | screenshot | states | aria | rtl | forced-colors |
|------|:--:|:--|:--:|:--:|:--:|
${rows.join('\n')}

## Components without a dedicated case

${gaps.length ? gaps.map((g) => `- ${g}`).join('\n') : '_none_'}

_These are covered indirectly (e.g. inside a pattern/composition) or are structural. Add a\ndedicated case if you want per-component screenshot + ARIA coverage._
`

writeFileSync(join(root, 'docs/visual-coverage.md'), md)
console.log(
  `\n  visual-coverage: ${allCases.length} cases · ${screenshots.size} screenshots · ${stateMap.size} state-shot · ${ariaSet.size} aria · ${rtlSet.size} rtl · ${fcSet.size} forced-colors`,
)
console.log(`  components: ${components.length - gaps.length}/${components.length} with a dedicated case`)
console.log('  wrote docs/visual-coverage.md\n')
